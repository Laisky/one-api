const (
	// effectiveCatalogSnapshotUpdateEnv names the environment variable that
	// rewrites the committed golden instead of comparing against it.
	effectiveCatalogSnapshotUpdateEnv = "ONEAPI_UPDATE_CATALOG_SNAPSHOT"
	// effectiveCatalogSnapshotPath is the committed golden, relative to this package.
	effectiveCatalogSnapshotPath = "testdata/effective_catalog_snapshot.txt"
	// effectiveCatalogSnapshotMaxReported bounds how many changed keys a failure prints.
	effectiveCatalogSnapshotMaxReported = 40
)

// effectiveCatalogSnapshotTime is the fixed request start time every model is
// resolved at, so time-of-day pricing windows produce the same snapshot on every
// run. It is a Wednesday at 12:00 Asia/Shanghai, outside the DeepSeek off-peak window.
var effectiveCatalogSnapshotTime = time.Date(2026, time.November, 18, 4, 0, 0, 0, time.UTC)

// TestEffectiveCatalogSnapshot pins every channel type's advertised catalog and
// the pricing billing resolves for each advertised model to a committed golden.
//
// Any change to an adaptor's model list, the provider/global pricing layers, the
// operator-tariff policy, or a single price field changes the golden and must be
// reviewed as a diff. Regenerate it with
// ONEAPI_UPDATE_CATALOG_SNAPSHOT=1 go test ./test -run TestEffectiveCatalogSnapshot -count=1
// and review `git diff test/testdata/effective_catalog_snapshot.txt` before committing.
func TestEffectiveCatalogSnapshot(t *testing.T) {
	pricing.InitializeGlobalPricingManager(relay.GetAdaptor)
	got := buildEffectiveCatalogSnapshot()

	if os.Getenv(effectiveCatalogSnapshotUpdateEnv) == "1" {
		require.NoError(t, os.MkdirAll(filepath.Dir(effectiveCatalogSnapshotPath), 0o755))
		require.NoError(t, os.WriteFile(effectiveCatalogSnapshotPath, []byte(got), 0o644))
		t.Logf("rewrote %s (%d bytes); review the diff before committing", effectiveCatalogSnapshotPath, len(got))
		return
	}

	wantBytes, err := os.ReadFile(effectiveCatalogSnapshotPath)
	require.NoErrorf(t, err, "read %s; generate it with %s=1 go test ./test -run TestEffectiveCatalogSnapshot -count=1",
		effectiveCatalogSnapshotPath, effectiveCatalogSnapshotUpdateEnv)
	want := string(wantBytes)
	if want == got {
		return
	}

	require.Failf(t, "effective model catalog or pricing changed",
		"The advertised catalog or the pricing billing resolves no longer matches %s.\n"+
			"If the change is intended, regenerate the golden with\n"+
			"    %s=1 go test ./test -run TestEffectiveCatalogSnapshot -count=1\n"+
			"and REVIEW `git diff %s` line by line: every added, removed or re-priced model "+
			"changes what users are billed.\n\n%s",
		effectiveCatalogSnapshotPath, effectiveCatalogSnapshotUpdateEnv,
		"test/"+effectiveCatalogSnapshotPath,
		describeEffectiveCatalogSnapshotDiff(want, got, effectiveCatalogSnapshotMaxReported))
}

// buildEffectiveCatalogSnapshot renders the canonical snapshot text.
//
// Channel types are enumerated exactly like TestEveryAdvertisedModelIsPricedByItsChannel:
// the billing adaptor comes from pricingAdaptorForChannel and the advertised list
// mirrors controller/model.go. Every line is tab-separated: channel type, channel
// name, model (or "*" for the per-channel summary), then space-separated
// key=value fields. Lines are sorted by channel type and model. A channel type
// whose name and entries are identical to an earlier one is written as a single
// "same_as=<earlier type>" summary line, so a shared table appears once.
//
// Returns: the full snapshot, ending with a newline.
func buildEffectiveCatalogSnapshot() string {
	var b strings.Builder
	b.WriteString("# Effective model catalog and pricing per channel type, as billing resolves it.\n")
	b.WriteString("# Generated by TestEffectiveCatalogSnapshot; do not edit by hand. Regenerate with\n")
	b.WriteString("#   " + effectiveCatalogSnapshotUpdateEnv + "=1 go test ./test -run TestEffectiveCatalogSnapshot -count=1\n")
	b.WriteString("# Resolved at " + effectiveCatalogSnapshotTime.Format(time.RFC3339) + " with no channel overrides.\n")
	b.WriteString("# Ratios are internal quota units per token (USD/1M = ratio / 0.5); src is the pricing layer that answered.\n")
	b.WriteString("# Columns: channel type, channel name, model (* = channel summary), fields. same_as=N repeats channel N verbatim.\n")

	firstChannelForBody := map[string]int{}
	for channelType := 1; channelType < channeltype.Dummy; channelType++ {
		provider := pricingAdaptorForChannel(channelType)
		if provider == nil {
			continue
		}
		name, summary, entries := snapshotChannelEntries(channelType, provider)
		body := name + "\n" + summary + "\n" + strings.Join(entries, "\n")
		if first, seen := firstChannelForBody[body]; seen {
			fmt.Fprintf(&b, "%d\t%s\t*\tsame_as=%d %s\n", channelType, name, first, summary)
			continue
		}
		firstChannelForBody[body] = channelType

		fmt.Fprintf(&b, "%d\t%s\t*\t%s\n", channelType, name, summary)
		for _, entry := range entries {
			fmt.Fprintf(&b, "%d\t%s\t%s\n", channelType, name, entry)
		}
	}
	return b.String()
}

// snapshotChannelEntries renders one channel type's advertised catalog.
//
// Parameters:
//   - channelType: the channel type being enumerated.
//   - provider: the billing adaptor for channelType.
//
// Returns: the channel name, the summary fields, and one "model<TAB>fields"
// entry per distinct advertised model in ascending model order.
func snapshotChannelEntries(channelType int, provider adaptor.Adaptor) (string, string, []string) {
	name, models := snapshotAdvertisedModels(channelType, provider)
	listed := make(map[string]int, len(models))
	for _, modelName := range models {
		listed[modelName]++
	}

	sources := map[string]int{}
	entries := make([]string, 0, len(listed))
	for _, modelName := range snapshotSortedKeys(listed) {
		source, fields := snapshotModelFields(provider, modelName)
		sources[source]++
		if listed[modelName] > 1 {
			fields = append([]string{"listed=" + strconv.Itoa(listed[modelName])}, fields...)
		}
		entries = append(entries, modelName+"\t"+strings.Join(fields, " "))
	}

	summary := []string{"advertised=" + strconv.Itoa(len(listed))}
	for _, source := range snapshotSortedKeys(sources) {
		summary = append(summary, "src."+source+"="+strconv.Itoa(sources[source]))
	}
	return name, strings.Join(summary, " "), entries
}

// snapshotAdvertisedModels returns the channel name and advertised model list the
// way controller/model.go builds it: OpenAI-compatible channels advertise the
// sub-provider catalog, every other channel its adaptor's own list.
//
// Parameters:
//   - channelType: the channel type being enumerated.
//   - provider: the billing adaptor for channelType.
//
// Returns: the display name and the advertised model IDs, possibly with duplicates.
func snapshotAdvertisedModels(channelType int, provider adaptor.Adaptor) (string, []string) {
	name, models := openai.GetCompatibleChannelMeta(channelType)
	if channeltype.ToAPIType(channelType) != 0 {
		return provider.GetChannelName(), provider.GetModelList()
	}
	return name, models
}

// snapshotModelFields resolves one advertised model the way billing does and
// renders its canonical fields.
//
// Parameters:
//   - provider: the billing adaptor (already bound to its channel type).
//   - modelName: the advertised model ID.
//
// Returns: the pricing source label ("provider", "global", "operator_tariff" or
// "none") and the sorted-by-schema key=value fields that describe the model.
func snapshotModelFields(provider adaptor.Adaptor, modelName string) (string, []string) {
	var flags []string
	if dynamic, ok := provider.(adaptor.DynamicVideoPricingAdaptor); ok && dynamic.SupportsDynamicVideoPricing(modelName) {
		flags = append(flags, "dynamic_video=true")
	}
	if policy, ok := provider.(interface{ RequiresExplicitRealtimePricing(string) bool }); ok &&
		policy.RequiresExplicitRealtimePricing(modelName) {
		flags = append(flags, "explicit_realtime=true")
	}

	if snapshotRequiresOperatorTariff(provider, modelName) {
		fields := append([]string{"src=operator_tariff"}, flags...)
		return "operator_tariff", append(fields, snapshotMetadataLimitFields(provider, modelName)...)
	}

	effective, found := pricing.ResolveModelConfig(modelName, nil, provider, effectiveCatalogSnapshotTime)
	if !found {
		return "none", append([]string{"src=none"}, flags...)
	}

	source := "global"
	raw, inProvider := provider.GetDefaultModelPricing()[modelName]
	if inProvider {
		source = "provider"
	} else {
		raw, _ = pricing.GetGlobalModelConfig(modelName)
	}

	fields := append([]string{"src=" + source}, flags...)
	fields = append(fields, "ratio="+formatSnapshotFloat(effective.Ratio))
	if active := pricing.ActiveTimeWindowName(raw, effectiveCatalogSnapshotTime); active != "" {
		fields = append(fields, "active_window="+strconv.Quote(active))
	}
	effective.Ratio = 0
	effective.TimeWindows = nil
	fields = appendSnapshotValue(fields, "", effective, snapshotIgnoredModelConfigFields)
	for i, window := range raw.TimeWindows {
		fields = appendSnapshotValue(fields, "time_windows["+strconv.Itoa(i)+"]", window, snapshotIgnoredModelConfigFields)
	}
	return source, fields
}

// snapshotRequiresOperatorTariff reports whether billing refuses every provider
// and global tariff for modelName on provider.
//
// Parameters:
//   - provider: the billing adaptor.
//   - modelName: the advertised model ID.
//
// Returns: true when only an operator-configured channel tariff can price the model.
func snapshotRequiresOperatorTariff(provider adaptor.Adaptor, modelName string) bool {
	return adaptor.RequiresOperatorTariff(provider, modelName)
}

// snapshotMetadataLimitFields renders the admission limits an operator-tariff
// model still carries. Prices are deliberately omitted because billing never uses them.
//
// Parameters:
//   - provider: the billing adaptor.
//   - modelName: the advertised model ID.
//
// Returns: context_length, max_output_tokens and max_tokens fields when non-zero.
func snapshotMetadataLimitFields(provider adaptor.Adaptor, modelName string) []string {
	metadata, found := pricing.ResolveModelMetadata(modelName, provider, effectiveCatalogSnapshotTime)
	if !found {
		return []string{"metadata=none"}
	}
	var fields []string
	if metadata.ContextLength != 0 {
		fields = append(fields, "context_length="+strconv.Itoa(int(metadata.ContextLength)))
	}
	if metadata.MaxOutputTokens != 0 {
		fields = append(fields, "max_output_tokens="+strconv.Itoa(int(metadata.MaxOutputTokens)))
	}
	if metadata.MaxTokens != 0 {
		fields = append(fields, "max_tokens="+strconv.Itoa(int(metadata.MaxTokens)))
	}
	return fields
}
